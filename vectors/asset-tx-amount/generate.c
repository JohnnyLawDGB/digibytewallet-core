// Vectors for BRAssetTxAmount.h (BRAssetTxActivityAmount): the header's answers on a fixed corpus, so a
// platform's binding test (iOS: AssetTxAmountTests) can be held to the same answers without its own reading of
// the rule. These are the header written down, not independent answers: the independent expectations are the
// hand-written values in the host KAT asset_tx_amount_kat (Android repo), taken from Android v4.1.4's
// AssetManager (assetTokenCountForTx, receivedBackedUnits, assetAmountForTx), UtxoDao.getResolvedAssetIdForTx
// and the end states of its UnbackedAssetCreditTest and AssetArithmeticNeverWrapsTest; that KAT checks this
// file is current and that every answer in it is the hand-written one.
//
// The corpus is corpus.txt (the line format is read.h's, without the answer); this writes each of its lines
// with " -> <status> <units> <assetId>" appended. Always the shipped rule: ASSET_TX_AMOUNT_UNFIXED is forced
// to 0 here.
//
// Build (it calls BRDigiAsset.c's carrier rule and the transaction code): with the core's objects, as
// asset_tx_amount_kat's run.sh does, then
//   ./gen vectors/asset-tx-amount/corpus.txt > vectors/asset-tx-amount/vectors.txt
// It exits 1, writing nothing, when a line does not read.

#undef ASSET_TX_AMOUNT_UNFIXED
#define ASSET_TX_AMOUNT_UNFIXED 0
#include <stdio.h>
#include "read.h"

int main(int argc, char **argv)
{
    static char out[64 * 4096];
    char line[2048];
    size_t used = 0;
    FILE *f;

    if (argc != 2 || ! (f = fopen(argv[1], "r"))) return 1;
    used += (size_t)snprintf(out + used, sizeof(out) - used,
        "# BRAssetTxAmount.h vectors: the header's answers, written down. Generated by vectors/asset-tx-amount/generate.c\n"
        "# from corpus.txt; do not edit (asset_tx_amount_kat checks it is current). The line format is read.h's.\n");
    while (fgets(line, sizeof(line), f)) {
        TxaCase c;
        BRAssetTxAmount a;

        line[strcspn(line, "\r\n")] = 0;
        if (line[0] == '#' || line[0] == 0) continue;
        if (! txaRead(line, &c) || c.hasAnswer) { fclose(f); return 1; }
        a = txaRun(&c);
        used += (size_t)snprintf(out + used, sizeof(out) - used, "%s -> %s %" PRId64 " %s\n", line, txaStatusName(a.status),
                                 a.units, a.assetId ? a.assetId : "-");
        txaFree(&c);
        if (used >= sizeof(out)) { fclose(f); return 1; }
    }
    fclose(f);
    fputs(out, stdout);
    return 0;
}
