// Vectors for BRDerivationProfiles.h and BRRecoveryDerive.h: the profile table and the first
// RECOVERY_VECTOR_COUNT receive and change addresses of every profile, in every encoding it is probed as,
// for four seeds (two BIP39 test mnemonics, each without and with the passphrase "TREZOR"), plus the
// seed function's refusals. Like vectors/tx-rows/, these are the headers written down, so each platform's
// binding test can be held to the answers the host KAT holds the headers to. They are not an
// independent source: the independent checks are vectors/derivation/ (generated without the core) and
// Android's bridge (jni_derive.c), which derivation_profiles_kat compares the headers with for every
// profile at the full starting window, and which checks this file is current.
//
// Always the shipped table and rule: the RED seams are undefined here. Mainnet (BRNetworkIsTestnet() is 0).
//
// Regenerate, from this directory (CORE = the core checkout's root):
//   CORE=../..; cc -w -include stdint.h -I $CORE -I $CORE/secp256k1/include -o /tmp/recovery_derivation_vectors \
//     generate.c $CORE/BRBIP32Sequence.c $CORE/BRBIP39Mnemonic.c $CORE/BRKey.c $CORE/BRAddress.c \
//     $CORE/BRBase58.c $CORE/BRBech32.c $CORE/BRCrypto.c $CORE/BRNetwork.c $CORE/BRSet.c \
//     $CORE/crypto/groestl.c $CORE/crypto/skein.c $CORE/crypto/qubit.c $CORE/crypto/odocrypt.c \
//     $CORE/crypto/sha3/*.c -lm -lpthread && /tmp/recovery_derivation_vectors > vectors.txt

#undef DERIVATION_PROFILES_RED
#undef RECOVERY_SEED_NUL_RED
#undef RECOVERY_ENCODER_RED
#include "BRRecoveryDerive.h"

#include <inttypes.h>
#include <stdio.h>

#define RECOVERY_VECTOR_COUNT 10

static const struct { const char *mnemonic, *passphrase; } SEEDS[] = {
    { "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about", "" },
    { "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about", "TREZOR" },
    { "legal winner thank year wave sausage worth useful legal winner thank yellow", "" },
    { "legal winner thank year wave sausage worth useful legal winner thank yellow", "TREZOR" },
};

static void printPath(const BRDerivationProfile *p)
{
    printf("m");
    for (size_t i = 0; i < p->pathLen; i++) {
        printf("/%" PRIu32 "%s", p->path[i] & ~BR_DERIVATION_HARD, (p->path[i] & BR_DERIVATION_HARD) ? "'" : "");
    }
}

static void refusal(const char *id, const char *phrase, size_t phraseLen, const char *pass, size_t passLen)
{
    uint8_t seed[BR_RECOVERY_SEED_LEN];
    int ok = BRRecoveryMnemonicToSeed(seed, phrase, phraseLen, pass, passLen);

    printf("seed-refused %s %s\n", id, ok ? "accepted" : "refused");
    mem_clean(seed, sizeof(seed));
}

int main(void)
{
    static char out[2 * RECOVERY_VECTOR_COUNT * BR_RECOVERY_ADDRESS_SLOT];
    size_t count = 0;
    const BRDerivationProfile *profiles = BRDerivationProfiles(&count);

    printf("# BRDerivationProfiles.h / BRRecoveryDerive.h vectors: the headers' answers, written down.\n");
    printf("# Generated by vectors/recovery-derivation/generate.c; do not edit (derivation_profiles_kat checks it is current).\n");
    printf("# network: mainnet\n");
    printf("# profile <i> <path> hmac=\"<key>\" formats=<f,...> native=<0|1> gap=<external>,<internal> label=\"<label>\"\n");
    printf("#   formats: 0 P2PKH, 1 P2WPKH, 2 P2SH-P2WPKH, 3 P2TR; the first is the profile's own\n");
    printf("# seed <s> mnemonic=\"...\" passphrase=\"...\" <64-byte BIP39 seed, hex>\n");
    printf("# addr <s> <profile> <format> <chain> <index> <address>   (first %d of each chain)\n", RECOVERY_VECTOR_COUNT);
    printf("# seed-refused <case> <accepted|refused>\n");

    for (size_t i = 0; i < count; i++) {
        const BRDerivationProfile *p = &profiles[i];

        printf("profile %zu ", i);
        printPath(p);
        printf(" hmac=\"%s\" formats=", p->hmacKey);
        for (size_t f = 0; f < p->formatCount; f++) printf("%s%d", f ? "," : "", p->formats[f]);
        printf(" native=%d gap=%" PRId32 ",%" PRId32 " label=\"%s\"\n", p->isNative, p->gapExternal, p->gapInternal,
               p->label);
    }

    for (size_t s = 0; s < sizeof(SEEDS) / sizeof(SEEDS[0]); s++) {
        uint8_t seed[BR_RECOVERY_SEED_LEN];

        if (! BRRecoveryMnemonicToSeed(seed, SEEDS[s].mnemonic, strlen(SEEDS[s].mnemonic),
                                       SEEDS[s].passphrase, strlen(SEEDS[s].passphrase))) return 1;
        printf("seed %zu mnemonic=\"%s\" passphrase=\"%s\" ", s, SEEDS[s].mnemonic, SEEDS[s].passphrase);
        for (size_t b = 0; b < sizeof(seed); b++) printf("%02x", seed[b]);
        printf("\n");

        for (size_t i = 0; i < count; i++) {
            const BRDerivationProfile *p = &profiles[i];

            for (size_t f = 0; f < p->formatCount; f++) {
                const size_t slots = 2 * RECOVERY_VECTOR_COUNT;

                if (! BRRecoveryDeriveAddresses(out, slots, seed, sizeof(seed), p->hmacKey, p->path, p->pathLen,
                                                RECOVERY_VECTOR_COUNT, RECOVERY_VECTOR_COUNT, p->formats[f])) return 1;
                for (size_t k = 0; k < slots; k++) {
                    uint32_t chain, index;
                    const char *addr = BRRecoveryDerivedSlot(out, slots, RECOVERY_VECTOR_COUNT, k, &chain, &index);

                    printf("addr %zu %zu %d %" PRIu32 " %" PRIu32 " %s\n", s, i, p->formats[f], chain, index,
                           addr ? addr : "-");
                }
            }
        }
        mem_clean(seed, sizeof(seed));
    }

    {
        static char longPhrase[BR_RECOVERY_PHRASE_MAX + 1], longPass[BR_RECOVERY_PASSPHRASE_MAX + 1];
        const char *m = SEEDS[0].mnemonic;

        memset(longPhrase, 'a', sizeof(longPhrase));
        memset(longPass, 'a', sizeof(longPass));
        refusal("passphrase_with_nul", m, strlen(m), "abc\0evil", 8);
        refusal("phrase_511_bytes", longPhrase, BR_RECOVERY_PHRASE_MAX, NULL, 0);
        refusal("phrase_512_bytes", longPhrase, BR_RECOVERY_PHRASE_MAX + 1, NULL, 0);
        refusal("passphrase_128_bytes", m, strlen(m), longPass, BR_RECOVERY_PASSPHRASE_MAX);
        refusal("passphrase_129_bytes", m, strlen(m), longPass, BR_RECOVERY_PASSPHRASE_MAX + 1);
        refusal("null_phrase", NULL, 0, NULL, 0);
    }
    return 0;
}
