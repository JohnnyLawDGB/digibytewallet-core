// Vectors for BRTxRows.h: the header's answers for its pure rules (DATE, AMOUNT, FEE, ORDER) on a
// fixed corpus, so each platform's binding test (L2) can be held to the same answers the host KATs
// hold the header to. Like vectors/cf-restore-preflight/, these are the header written down, not an
// independent source: the independent expectations are the hand-written values in the host KATs
// (tx_rows_order_kat, tx_rows_amount_kat), and tx_rows_order_kat checks this file is current.
//
// Always the shipped rule: TX_ROWS_UNFIXED is forced to 0 here.
//
// Regenerate, from this directory:
//   cc -I ../.. -I ../../secp256k1/include -o /tmp/tx_rows_vectors generate.c && /tmp/tx_rows_vectors > vectors.txt

#undef TX_ROWS_UNFIXED
#define TX_ROWS_UNFIXED 0
#include "BRTxRows.h"

#include <stdio.h>
#include <inttypes.h>

static const char *ruleName(BRTxRowAmountRule r)
{
    switch (r) {
    case BRTxRowAmountNet: return "NET";
    case BRTxRowAmountPayee: return "PAYEE";
    case BRTxRowAmountDigiDollar: return "DIGIDOLLAR";
    default: return "?";
    }
}

// An order case: rows given as shownTimestamp, blockHeight, walletIndex.
typedef struct { uint32_t ts, height, index; } OrderRow;

static void order(const char *id, const OrderRow *in, size_t n)
{
    BRTxRow rows[16];
    size_t i;

    memset(rows, 0, sizeof(rows));
    for (i = 0; i < n; i++) {
        rows[i].shownTimestamp = in[i].ts;
        rows[i].timestamp = in[i].ts;
        rows[i].blockHeight = in[i].height;
        rows[i].walletIndex = in[i].index;
    }
    qsort(rows, n, sizeof(rows[0]), _BRTxRowQsortCompare);
    printf("order %s", id);
    for (i = 0; i < n; i++) {
        printf(" %" PRIu32 ":%" PRIu32 ":%" PRIu32, in[i].ts, in[i].height, in[i].index);
    }
    printf(" ->");
    for (i = 0; i < n; i++) printf(" %" PRIu32, rows[i].walletIndex);
    printf("\n");
}

int main(void)
{
    const uint32_t U = TX_UNCONFIRMED;

    printf("# BRTxRows.h vectors: the header's answers, written down. Generated by vectors/tx-rows/generate.c;\n");
    printf("# do not edit (tx_rows_order_kat checks it is current).\n");
    printf("# shown <timestamp> <now> <shownTimestamp>\n");
    printf("# fee <wallet fee> <row fee>            (18446744073709551615 = BR_TX_ROW_FEE_UNKNOWN)\n");
    printf("# amount <isDigiDollar> <ownsInput> <received> <sent> <toOthers> <rule> <amount>\n");
    printf("# order <id> <shownTimestamp>:<blockHeight>:<walletIndex>... -> <walletIndex of each row, in listed order>...\n");
    printf("#   (blockHeight 2147483647 = TX_UNCONFIRMED)\n");

    {
        const uint32_t ts[] = { 0, 1, 1700000000, UINT32_MAX };
        const uint32_t now[] = { 0, 1, 1762560000, UINT32_MAX };
        for (size_t i = 0; i < sizeof(ts) / sizeof(ts[0]); i++)
            for (size_t j = 0; j < sizeof(now) / sizeof(now[0]); j++)
                printf("shown %" PRIu32 " %" PRIu32 " %" PRIu32 "\n", ts[i], now[j], BRTxRowShownTimestamp(ts[i], now[j]));
    }

    {
        const uint64_t fees[] = { 0, 1, 14100, UINT64_MAX - 1, UINT64_MAX };
        for (size_t i = 0; i < sizeof(fees) / sizeof(fees[0]); i++)
            printf("fee %" PRIu64 " %" PRIu64 "\n", fees[i], BRTxRowFeeFor(fees[i]));
    }

    {
        // received, sent, toOthers triples: a receive, a send with change, a send of everything, a
        // self-send, a missing-parent send (sent 0), a partial-parent send, a DigiAsset marker send,
        // a DigiDollar mint shape, and the saturation edges.
        const uint64_t v[][3] = {
            { 100000000, 0, 0 },
            { 0, 0, 0 },
            { 389990000, 500000000, 110000000 },
            { 0, 500000000, 499990000 },
            { 499990000, 500000000, 0 },
            { 389990000, 0, 110000000 },
            { 389990000, 300000000, 110000000 },
            { 49978000, 50000000, 6000 },
            { 10000000, 60000000, 49990000 },
            { UINT64_MAX, 0, 0 },
            { 0, UINT64_MAX, 1 },
            { 0, 0, UINT64_MAX },
            { 0, 0, (uint64_t)INT64_MAX },
            { 0, 0, (uint64_t)INT64_MAX + 1 },
            { (uint64_t)INT64_MAX, 0, 0 },
            { 0, (uint64_t)INT64_MAX, 1 },
            { 0, (uint64_t)INT64_MAX + 1, 1 },
        };
        for (size_t i = 0; i < sizeof(v) / sizeof(v[0]); i++) {
            for (int dd = 0; dd <= 1; dd++) {
                for (int owns = 0; owns <= 1; owns++) {
                    BRTxRowAmountRule r = BRTxRowAmountRuleFor(dd, owns, v[i][2]);
                    printf("amount %d %d %" PRIu64 " %" PRIu64 " %" PRIu64 " %s %" PRId64 "\n", dd, owns,
                           v[i][0], v[i][1], v[i][2], ruleName(r), BRTxRowAmountFor(r, v[i][0], v[i][1], v[i][2]));
                }
            }
        }
    }

    {
        // Order cases.
        struct { const char *id; OrderRow r[8]; size_t n; } c[] = {
            { "date_desc", { {100, 10, 0}, {300, 30, 1}, {200, 20, 2} }, 3 },
            { "date_over_height", { {300, 10, 0}, {100, 30, 1} }, 2 },
            { "height_breaks_date_tie", { {100, 10, 0}, {100, 30, 1}, {100, 20, 2} }, 3 },
            { "index_breaks_full_tie", { {100, 10, 2}, {100, 10, 0}, {100, 10, 1} }, 3 },
            { "pending_now_on_top", { {1700000000, 23000000, 0}, {1762560000, U, 1}, {1700000100, 23000005, 2} }, 3 },
            { "old_pending_not_on_top", { {1500000000, U, 0}, {1700000000, 23000000, 1} }, 2 },
            { "pending_tie_above_confirmed", { {1762560000, 23000000, 0}, {1762560000, U, 1} }, 2 },
            { "pending_tie_by_index", { {1762560000, U, 1}, {1762560000, U, 0} }, 2 },
            { "edges", { {0, 0, 0}, {UINT32_MAX, 0, 1}, {0, UINT32_MAX, 2}, {UINT32_MAX, UINT32_MAX, 3}, {0, U, 4} }, 5 },
        };
        for (size_t i = 0; i < sizeof(c) / sizeof(c[0]); i++) {
            order(c[i].id, c[i].r, c[i].n);
        }
    }
    return 0;
}
